export const locale = ref("zh-CN");
export const isDark = ref(
  typeof document !== "undefined" &&
    document.documentElement.getAttribute("data-theme") === "dark"
);

function normalizeLocale(raw) {
  if (typeof raw !== "string" || !raw) return "zh-CN";
  if (raw.toLowerCase().startsWith("zh")) return "zh-CN";
  return "en-US";
}

export function applyHostContext(ctx, bridge) {
  const nextLocale = normalizeLocale(ctx?.locale || bridge?.getLocale?.() || "zh-CN");
  locale.value = nextLocale;
  const dark =
    typeof ctx?.isDark === "boolean"
      ? ctx.isDark
      : typeof document !== "undefined" &&
        document.documentElement.getAttribute("data-theme") === "dark";
  isDark.value = dark;
  if (typeof document !== "undefined") {
    document.documentElement.setAttribute("data-theme", dark ? "dark" : "light");
    document.documentElement.lang = nextLocale;
    const hostTitle = bridge?.t?.("views.control.title", "") || bridge?.t?.("pages.control.title", "");
    document.title = hostTitle || MESSAGES[nextLocale]["page.title"];
  }
}

export function t(key, params = null) {
  const lang = locale.value in MESSAGES ? locale.value : "zh-CN";
  let text = MESSAGES[lang]?.[key] ?? MESSAGES["zh-CN"]?.[key] ?? key;
  if (params && typeof text === "string") {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return text;
}


